(function(){
  var $ = function(id){ return document.getElementById(id); };
  var q = $('f-q'), sev = $('f-sev'), cat = $('f-cat'), pg = $('f-page'), per = $('f-persona');
  var items = Array.prototype.slice.call(document.querySelectorAll('.issue'));
  var total = items.length;
  function apply(){
    if (!q) return;
    var text = q.value.trim().toLowerCase(), shown = 0;
    items.forEach(function(el){
      var ok = (!text || el.getAttribute('data-q').indexOf(text) !== -1)
        && (!sev.value || el.getAttribute('data-sev') === sev.value)
        && (!cat.value || el.getAttribute('data-cat') === cat.value)
        && (!pg.value || el.getAttribute('data-page') === pg.value)
        && (!per.value || el.getAttribute('data-personas').split('|').indexOf(per.value) !== -1);
      el.hidden = !ok;
      if (ok) shown++;
    });
    $('issue-count').textContent = '(' + (shown === total ? total : shown + ' of ' + total) + ')';
    $('no-match').hidden = shown !== 0 || total === 0;
  }
  [q, sev, cat, pg, per].forEach(function(el){ if (el) { el.addEventListener('input', apply); el.addEventListener('change', apply); } });
  var reset = $('f-reset');
  if (reset) reset.addEventListener('click', function(){ q.value = ''; sev.value = ''; cat.value = ''; pg.value = ''; per.value = ''; apply(); });
  function openIssue(id){
    var el = document.getElementById(id);
    if (el && el.tagName === 'DETAILS') { el.hidden = false; el.open = true; el.scrollIntoView({ block: 'start' }); }
  }
  Array.prototype.forEach.call(document.querySelectorAll('a.jump'), function(a){
    a.addEventListener('click', function(e){ e.preventDefault(); openIssue(a.getAttribute('data-id')); history.replaceState(null, '', '#' + a.getAttribute('data-id')); });
  });
  if (location.hash) openIssue(decodeURIComponent(location.hash.slice(1)));
})();
