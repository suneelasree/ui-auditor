const MIME: Record<string, string> = {
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.webp': 'image/webp',
  '.gif': 'image/gif',
};
/** Per-image and total caps keep the single file a sane size. */
const MAX_IMAGE_BYTES = 2_500_000;
const MAX_TOTAL_BYTES = 40_000_000;

interface Img {
  uri: string;
  width?: number;
  height?: number;
}

/** Reads images from the run dir once and turns them into data URIs. Missing / oversized files are skipped. */
class ImageEmbedder {
  private cache = new Map<string, Img | null>();
  private total = 0;
  constructor(private runDir: string) {}

  get(rel: string | undefined): Img | null {
    if (!rel) return null;
    if (this.cache.has(rel)) return this.cache.get(rel)!;
    const img = this.load(rel);
    this.cache.set(rel, img);
    return img;
  }

  private load(rel: string): Img | null {
    const mime = MIME[extname(rel).toLowerCase()];
    if (!mime) return null;
    const abs = resolve(this.runDir, rel);
    const r = relative(resolve(this.runDir), abs);
    if (r.startsWith('..') || isAbsolute(r)) return null; // stay inside the run dir
    try {
      const size = statSync(abs).size;
      if (size > MAX_IMAGE_BYTES || this.total + size > MAX_TOTAL_BYTES) return null;
      const buf = readFileSync(abs);
      this.total += buf.length;
      return { uri: `data:${mime};base64,${buf.toString('base64')}`, ...imageSize(buf) };
    } catch {
      return null;
    }
  }
}

function imageSize(buf: Buffer): { width?: number; height?: number } {
  // PNG: IHDR right after the 8-byte signature.
  if (buf.length > 24 && buf.readUInt32BE(0) === 0x89504e47) return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
  // JPEG: walk segments to the first SOFn marker.
  if (buf.length > 4 && buf[0] === 0xff && buf[1] === 0xd8) {
    let i = 2;
    while (i + 9 < buf.length) {
      if (buf[i] !== 0xff) return {};
      const marker = buf[i + 1];
      const len = buf.readUInt16BE(i + 2);
      if (marker >= 0xc0 && marker <= 0xcf && marker !== 0xc4 && marker !== 0xc8 && marker !== 0xcc) {
        return { height: buf.readUInt16BE(i + 5), width: buf.readUInt16BE(i + 7) };
      }
      i += 2 + len;
    }
  }
  return {};
}

/** One self-contained HTML file: inline CSS/JS, images as data URIs, no external requests. */
export function renderHtml(report: Report, runDir: string): string {
  const imgs = new ImageEmbedder(runDir);
  const byId = new Map(report.findings.map((f) => [f.id, f]));
  const date = report.finishedAt || report.createdAt;

  const body = [
    header(report, date),
    notes(report),
    summary(report, byId),
    navMap(report.nav, report.target),
    issues(report, imgs),
    designs(report, imgs),
    domainInsights(report),
    comparison(report, imgs),
    pages(report, imgs),
    agents(report),
    tests(report),
  ].join('\n');

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; img-src data:; style-src 'unsafe-inline'; script-src 'unsafe-inline'">
<meta name="referrer" content="no-referrer">
<title>UI Audit Report</title>
<style>${CSS}</style>
</head>
<body>
<nav class="toc" aria-label="Sections"><a href="#summary">Summary</a><a href="#nav">Navigation</a><a href="#issues">Issues</a>${report.findings.some((f) => f.designAlternative) ? '<a href="#designs">Designs</a>' : ''}${report.domainInsights.length ? '<a href="#insights">Domain</a>' : ''}${report.comparison ? '<a href="#comparison">Comparison</a>' : ''}<a href="#agents">Agents</a></nav>
<main>
${body}
<footer>Generated by UI Auditor &middot; run ${esc(report.id)} &middot; ${esc(date)}</footer>
</main>
<script>${JS}</script>
</body>
</html>
`;
}

