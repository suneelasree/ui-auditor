function header(r: Report, date: string): string {
  const target = safeHttpUrl(r.target);
  const deg = Math.max(0, Math.min(100, r.scores.overall));
  const circ = 2 * Math.PI * 52;
  const bars = CATEGORIES.map((c) => {
    const v = r.scores.byCategory[c];
    return `<div class="bar"><span class="bar-label">${c}</span><span class="bar-track"><span class="bar-fill ${scoreClass(v)}" style="width:${v}%"></span></span><span class="bar-val">${v}</span></div>`;
  }).join('');
  return `<header class="hero">
  <div class="hero-text">
    <p class="eyebrow">UI Audit Report</p>
    <h1>${target ? `<a href="${esc(target)}" rel="noopener noreferrer" target="_blank">${esc(r.target)}</a>` : esc(r.target)}</h1>
    <dl class="meta">
      <div><dt>Date</dt><dd>${esc(fmtDate(date))}</dd></div>
      <div><dt>Domain</dt><dd>${esc(r.domain.name)}${r.domain.detected ? ` <span class="muted">(detected, ${Math.round(r.domain.confidence * 100)}%)</span>` : ''}</dd></div>
      <div><dt>Pages</dt><dd>${r.summary.pagesAudited}</dd></div>
      <div><dt>Viewports</dt><dd>${esc(r.options.viewports.join(', '))}</dd></div>
    </dl>
  </div>
  <div class="score">
    <svg viewBox="0 0 120 120" class="ring" role="img" aria-label="Overall score ${r.scores.overall} out of 100">
      <circle cx="60" cy="60" r="52" class="ring-bg"/>
      <circle cx="60" cy="60" r="52" class="ring-fg ${scoreClass(deg)}" stroke-dasharray="${((deg / 100) * circ).toFixed(1)} ${circ.toFixed(1)}" transform="rotate(-90 60 60)"/>
      <text x="60" y="66" text-anchor="middle" class="ring-num">${r.scores.overall}</text>
    </svg>
    <div class="bars">${bars}</div>
  </div>
</header>`;
}

function notes(r: Report): string {
  if (r.notes.length === 0) return '';
  return `<section class="notes" role="note"><strong>Notes</strong><ul>${r.notes.map((n) => `<li>${esc(n)}</li>`).join('')}</ul></section>`;
}

function summary(r: Report, byId: Map<string, Finding>): string {
  const counts = SEVERITIES.map(
    (s) => `<div class="count c-${s.toLowerCase()}"><span class="count-n">${r.summary.counts[s] ?? 0}</span><span>${s}</span></div>`,
  ).join('');
  const top = r.summary.topIssues
    .map((id) => byId.get(id))
    .filter((f): f is Finding => !!f)
    .slice(0, 5)
    .map((f) => `<li><a href="#${esc(f.id)}" class="jump" data-id="${esc(f.id)}">${sevBadge(f.severity)} <b>${esc(f.id)}</b> ${esc(f.title)}</a> <span class="muted">${esc(f.category)} &middot; ${esc(pagePath(f.page))}</span></li>`)
    .join('');
  return `<section id="summary"><h2>Executive summary</h2>
<div class="counts">${counts}</div>
${top ? `<h3>Top issues</h3><ol class="top">${top}</ol>` : '<p>No issues found.</p>'}
</section>`;
}

function navMap(nav: NavGraph, target: string): string {
  if (nav.nodes.length === 0) return `<section id="nav"><h2>Navigation map</h2><p class="muted">No pages mapped.</p></section>`;
  const norm = (u: string) => u.replace(/#.*$/, '').replace(/\/+$/, '');
  const nodes = new Map(nav.nodes.map((n) => [norm(n.url), n]));
  const children = new Map<string, string[]>();
  for (const e of nav.edges) {
    const from = norm(e.from);
    const to = norm(e.to);
    if (!nodes.has(from) || !nodes.has(to) || from === to) continue;
    const list = children.get(from) ?? [];
    if (!list.includes(to)) list.push(to);
    children.set(from, list);
  }
  const broken = new Map<string, NavGraph['brokenLinks']>();
  for (const b of nav.brokenLinks) {
    const k = norm(b.from);
    broken.set(k, [...(broken.get(k) ?? []), b]);
  }

  // Spanning tree by BFS from the start page (or shallowest node).
  const sorted = [...nav.nodes].sort((a, b) => a.depth - b.depth);
  const root = nodes.has(norm(target)) ? norm(target) : norm(sorted[0].url);
  const parentOf = new Map<string, string | null>([[root, null]]);
  const queue = [root];
  while (queue.length) {
    const cur = queue.shift()!;
    for (const c of children.get(cur) ?? []) {
      if (!parentOf.has(c)) {
        parentOf.set(c, cur);
        queue.push(c);
      }
    }
  }
  const treeKids = new Map<string, string[]>();
  for (const [k, p] of parentOf) if (p) treeKids.set(p, [...(treeKids.get(p) ?? []), k]);

  const item = (key: string): string => {
    const n = nodes.get(key)!;
    const b = broken.get(key) ?? [];
    const flags = [
      n.deadEnd ? '<span class="flag bad">dead end</span>' : '',
      n.orphan ? '<span class="flag bad">orphan</span>' : '',
      b.length ? `<span class="flag bad">${b.length} broken link${b.length > 1 ? 's' : ''}</span>` : '',
    ].join('');
    const brokenList = b.length
      ? `<ul class="broken">${b.map((x) => `<li>&#10007; ${esc(x.href)} <span class="muted">(${x.status ?? 'no response'})</span></li>`).join('')}</ul>`
      : '';
    const kids = treeKids.get(key) ?? [];
    const cls = n.deadEnd || n.orphan || b.length ? ' class="problem"' : '';
    return `<li${cls}><span class="node"><b>${esc(pagePath(n.url))}</b> <span class="muted">${esc(n.title)}</span> <span class="deg">${n.inLinks} in / ${n.outLinks} out</span>${flags}</span>${brokenList}${kids.length ? `<ul>${kids.map(item).join('')}</ul>` : ''}</li>`;
  };

  const unreached = nav.nodes.map((n) => norm(n.url)).filter((k) => !parentOf.has(k));
  const deadEnds = nav.nodes.filter((n) => n.deadEnd).length;
  const orphans = nav.nodes.filter((n) => n.orphan).length;
  return `<section id="nav"><h2>Navigation map</h2>
<p class="muted">${nav.nodes.length} pages &middot; ${nav.edges.length} links &middot; <span class="bad-text">${deadEnds} dead ends &middot; ${orphans} orphans &middot; ${nav.brokenLinks.length} broken links</span></p>
<ul class="tree">${item(root)}</ul>
${unreached.length ? `<h3>Not reachable from the start page</h3><ul class="tree">${unreached.map(item).join('')}</ul>` : ''}
</section>`;
}

function issues(r: Report, imgs: ImageEmbedder): string {
  const pagesList = [...new Set(r.findings.map((f) => pagePath(f.page)))].sort();
  const usedCats = CATEGORIES.filter((c) => r.findings.some((f) => f.category === c));
  const usedPersonas = PERSONAS.filter((p) => r.findings.some((f) => f.foundBy.includes(p)));
  const select = (id: string, label: string, opts: readonly string[]) =>
    `<label>${label}<select id="${id}"><option value="">All</option>${opts.map((o) => `<option value="${esc(o)}">${esc(o)}</option>`).join('')}</select></label>`;

  const rows = r.findings.map((f) => issue(f, imgs)).join('\n');
  return `<section id="issues"><h2>Issues <span class="muted" id="issue-count">(${r.findings.length})</span></h2>
<div class="filters" role="search">
  <label class="search">Search<input id="f-q" type="search" placeholder="Title, selector, text..." autocomplete="off"></label>
  ${select('f-sev', 'Severity', SEVERITIES)}
  ${select('f-cat', 'Category', usedCats)}
  ${select('f-page', 'Page', pagesList)}
  ${select('f-persona', 'Persona', usedPersonas)}
  <button type="button" id="f-reset">Reset</button>
</div>
<div class="issue-list">${rows || '<p>No issues found.</p>'}</div>
<p id="no-match" class="muted" hidden>No issues match the filters.</p>
</section>`;
}

function issue(f: Finding, imgs: ImageEmbedder): string {
  const page = pagePath(f.page);
  const search = [f.id, f.title, f.category, f.severity, page, f.foundBy.join(' '), f.recommendation, ...f.evidence.map((e) => e.value)]
    .join(' ')
    .toLowerCase();
  const pageUrl = safeHttpUrl(f.page);
  const ev = f.evidence.map((e) => evidenceItem(e, imgs)).join('');
  return `<details class="issue" id="${esc(f.id)}" data-sev="${esc(f.severity)}" data-cat="${esc(f.category)}" data-page="${esc(page)}" data-personas="${esc(f.foundBy.join('|'))}" data-q="${esc(search)}">
<summary><span class="i-id">${esc(f.id)}</span>${sevBadge(f.severity)}<span class="i-title">${esc(f.title)}</span><span class="i-meta">${esc(f.category)} &middot; ${esc(page)} &middot; ${esc(viewportLabel(f.viewport))}</span></summary>
<div class="i-body">
  <p class="i-by"><b>Found by:</b> ${f.foundBy.map((p) => `<span class="chip">${esc(p)}</span>`).join(' ')} <span class="muted">${f.source === 'agent' ? 'AI agent' : 'rule'} &middot; fingerprint ${esc(f.fingerprint)}</span></p>
  <p><b>Page:</b> ${pageUrl ? `<a href="${esc(pageUrl)}" rel="noopener noreferrer" target="_blank">${esc(page)}</a>` : esc(page)} @ ${esc(viewportLabel(f.viewport))}</p>
  <div class="ea"><div><h4>Expected</h4><p>${esc(f.expected)}</p></div><div><h4>Actual</h4><p>${esc(f.actual)}</p></div></div>
  <h4>Steps to reproduce</h4><ol>${f.stepsToReproduce.map((s) => `<li>${esc(s)}</li>`).join('')}</ol>
  <h4>Evidence</h4><ul class="evidence">${ev}</ul>
  <h4>Recommendation</h4><p class="rec">${esc(f.recommendation)}</p>
  ${f.designAlternative ? `<p><a href="#design-${esc(f.id)}">See Good / Better design alternatives</a></p>` : ''}
</div>
</details>`;
}

function evidenceItem(e: EvidenceItem, imgs: ImageEmbedder): string {
  const img = imgs.get(e.screenshot);
  let shot = '';
  if (img) {
    let box = '';
    if (e.region && img.width && img.height) box = regionBox(e.region, img.width, img.height);
    shot = `<figure class="shot">${box ? `<span class="shot-wrap"><img src="${img.uri}" alt="Evidence screenshot" loading="lazy">${box}</span>` : `<img src="${img.uri}" alt="Evidence screenshot" loading="lazy">`}</figure>`;
  }
  return `<li><span class="ev-kind">${esc(e.kind)}</span> <code>${esc(e.value)}</code>${e.detail ? ` <span class="muted">${esc(e.detail)}</span>` : ''}${shot}</li>`;
}

function regionBox(r: Box, w: number, h: number): string {
  const pct = (v: number, of: number) => Math.max(0, Math.min(100, (v / of) * 100)).toFixed(2);
  return `<span class="region" style="left:${pct(r.x, w)}%;top:${pct(r.y, h)}%;width:${pct(r.width, w)}%;height:${pct(r.height, h)}%"></span>`;
}

function designs(r: Report, imgs: ImageEmbedder): string {
  const withAlt = r.findings.filter((f) => f.designAlternative);
  if (withAlt.length === 0) return '';
  const fig = (label: string, path: string | undefined, text: string) => {
    const img = imgs.get(path);
    return `<figure class="alt"><figcaption><b>${label}</b></figcaption>${img ? `<img src="${img.uri}" alt="${esc(label)} design" loading="lazy">` : '<div class="noimg">No screenshot</div>'}${text ? `<p>${esc(text)}</p>` : ''}</figure>`;
  };
  const items = withAlt
    .map((f) => {
      const d = f.designAlternative!;
      return `<article class="design" id="design-${esc(f.id)}"><h3><a href="#${esc(f.id)}" class="jump" data-id="${esc(f.id)}">${esc(f.id)}</a> ${esc(f.title)}</h3>
<div class="alts">${fig('Original', d.original, '')}${fig('Good (minimal fix)', d.goodScreenshot, d.goodSummary)}${fig('Better (redesign)', d.betterScreenshot, d.betterSummary)}</div></article>`;
    })
    .join('');
  return `<section id="designs"><h2>Design alternatives</h2>${items}</section>`;
}

function domainInsights(r: Report): string {
  if (r.domainInsights.length === 0) return '';
  return `<section id="insights"><h2>Domain insights <span class="muted">(${esc(r.domain.name)})</span></h2><ul class="insights">${r.domainInsights.map((d) => `<li>${esc(d)}</li>`).join('')}</ul></section>`;
}

function comparison(r: Report, imgs: ImageEmbedder): string {
  const c = r.comparison;
  if (!c || c.sites.length === 0) return '';
  const head = c.sites.map((s) => `<th>${esc(s.label)}${s.isTarget ? ' <span class="chip">you</span>' : ''}</th>`).join('');
  const best = (vals: number[]) => Math.max(...vals);
  const row = (label: string, vals: number[]) =>
    `<tr><th scope="row">${label}</th>${vals.map((v) => `<td class="${v === best(vals) ? 'best' : ''}">${v}</td>`).join('')}</tr>`;
  const rows = [row('<b>Overall</b>', c.sites.map((s) => s.scores.overall)), ...CATEGORIES.map((cat) => row(cat, c.sites.map((s) => s.scores.byCategory[cat])))].join('');
  const shots = c.sites
    .map((s) => ({ s, img: imgs.get(s.screenshot) }))
    .filter((x) => x.img)
    .map((x) => `<figure class="alt"><figcaption><b>${esc(x.s.label)}</b></figcaption><img src="${x.img!.uri}" alt="${esc(x.s.label)} home page" loading="lazy"></figure>`)
    .join('');
  const better = c.theyDoBetter
    .map((t) => {
      const img = imgs.get(t.screenshot);
      return `<article class="card"><h4>${esc(t.title)} <span class="muted">&middot; ${esc(t.competitor)}</span></h4><p>${esc(t.detail)}</p>${img ? `<img src="${img.uri}" alt="${esc(t.competitor)} example" loading="lazy">` : ''}</article>`;
    })
    .join('');
  const list = (items: string[]) => `<ul>${items.map((x) => `<li>${esc(x)}</li>`).join('')}</ul>`;
  return `<section id="comparison"><h2>Competitor comparison</h2>
<div class="table-wrap"><table class="cmp"><thead><tr><th>Category</th>${head}</tr></thead><tbody>${rows}</tbody></table></div>
${shots ? `<div class="alts">${shots}</div>` : ''}
${better ? `<h3>What they do better</h3><div class="cards">${better}</div>` : ''}
${c.youWin.length ? `<h3>Where you win</h3>${list(c.youWin)}` : ''}
${c.patternsToCopy.length ? `<h3>Patterns worth copying</h3>${list(c.patternsToCopy)}` : ''}
</section>`;
}

function pages(r: Report, imgs: ImageEmbedder): string {
  if (r.pages.length === 0) return '';
  const items = r.pages
    .map((p) => {
      const img = imgs.get(p.screenshot);
      return `<figure class="page-card">${img ? `<img src="${img.uri}" alt="Above the fold: ${esc(p.title)}" loading="lazy">` : '<div class="noimg">No screenshot</div>'}<figcaption><b>${esc(pagePath(p.url))}</b><br><span class="muted">${esc(p.title)}${p.requiresLogin ? ' &middot; login' : ''}</span></figcaption></figure>`;
    })
    .join('');
  return `<section id="pages"><details><summary><h2>Pages audited (${r.pages.length})</h2></summary><div class="page-grid">${items}</div></details></section>`;
}

function agents(r: Report): string {
  const rows = r.agents
    .map((a) => `<tr><td>${esc(a.name)}</td><td><span class="status st-${esc(a.status)}">${esc(a.status)}</span></td><td>${a.findings}</td><td>${a.dropped}</td><td>${esc(a.note ?? '')}</td></tr>`)
    .join('');
  return `<section id="agents"><h2>Agents</h2>${rows ? `<div class="table-wrap"><table><thead><tr><th>Agent</th><th>Status</th><th>Findings</th><th>Dropped</th><th>Notes</th></tr></thead><tbody>${rows}</tbody></table></div>` : '<p class="muted">No agent runs recorded.</p>'}</section>`;
}

function tests(r: Report): string {
  return `<section id="tests"><h2>Generated regression tests</h2>${
    r.generatedTests.length
      ? `<p class="muted">Playwright specs that fail against the audited site until the defects are fixed. Run with <code>npx playwright test ${esc('<run dir>')}/tests/generated</code>.</p><ul>${r.generatedTests.map((t) => `<li><code>${esc(t)}</code></li>`).join('')}</ul>`
      : '<p class="muted">No tests were generated.</p>'
  }</section>`;
}

// ---------- helpers ----------

function sevBadge(s: string): string {
  return `<span class="sev sev-${esc(s.toLowerCase())}">${esc(s)}</span>`;
}

function scoreClass(v: number): string {
  return v >= 90 ? 'good' : v >= 70 ? 'ok' : v >= 50 ? 'warn' : 'poor';
}

function fmtDate(iso: string): string {
  const d = new Date(iso);
  return Number.isNaN(d.getTime()) ? iso : d.toISOString().replace('T', ' ').replace(/\.\d+Z$/, ' UTC');
}

