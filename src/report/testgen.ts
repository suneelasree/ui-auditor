import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { VIEWPORT_SIZES, type EvidenceBundle, type Finding, type PageEvidence } from '../core/types.js';

const HEADER = `// Generated by UI Auditor. Do not edit by hand; re-run the audit to regenerate.
//
// These are regression checks for defects found during the audit. Each test asserts the
// EXPECTED (fixed) behaviour, so it currently FAILS against the audited site and should
// pass once the defect is fixed. Tests marked test.fixme could not be automated from the
// evidence alone; their steps are listed as comments.
`;

/**
 * Write one Playwright spec per page for Functional / Navigation findings (and hidden-CTA UX findings)
 * into <runDir>/tests/generated/. Returns paths relative to runDir with forward slashes.
 */
export function generateTests(findings: Finding[], bundle: EvidenceBundle, runDir: string): string[] {
  const byPage = new Map<string, { url: string; tests: string[] }>();
  for (const f of findings) {
    const pageEv = findPage(bundle, f.page);
    const hiddenCta = isHiddenCta(f, pageEv);
    if (f.category !== 'Functional' && f.category !== 'Navigation' && !hiddenCta) continue;
    const url = resolveUrl(f.page, bundle.startUrl);
    const entry = byPage.get(url) ?? { url, tests: [] };
    entry.tests.push(testFor(f, url, pageEv, hiddenCta));
    byPage.set(url, entry);
  }
  if (byPage.size === 0) return [];

  const outDir = join(runDir, 'tests', 'generated');
  mkdirSync(outDir, { recursive: true });
  const used = new Set<string>();
  const written: string[] = [];
  for (const { url, tests } of byPage.values()) {
    let slug = slugFor(url);
    for (let i = 2; used.has(slug); i++) slug = `${slugFor(url)}-${i}`;
    used.add(slug);
    const body = [
      HEADER,
      `import { test, expect } from '@playwright/test';`,
      ``,
      `const PAGE_URL = ${q(url)};`,
      ``,
      `test.describe(${q(`UI Auditor regression checks: ${pathOf(url)}`)}, () => {`,
      tests.join('\n\n'),
      `});`,
      ``,
    ].join('\n');
    const file = `${slug}.spec.ts`;
    writeFileSync(join(outDir, file), body);
    written.push(`tests/generated/${file}`);
  }
  return written;
}

function testFor(f: Finding, url: string, pageEv: PageEvidence | undefined, hiddenCta: boolean): string {
  const name = q(`${f.id}: ${f.title}`);
  const selectors = f.evidence.filter((e) => e.kind === 'selector').map((e) => e.value);

  // Hidden CTA: must be visible at the audited viewport.
  if (hiddenCta && f.viewport !== 'all' && selectors.length > 0) {
    const size = VIEWPORT_SIZES[f.viewport];
    return block(name, ['page'], [
      `await page.setViewportSize({ width: ${size.width}, height: ${size.height} });`,
      `await page.goto(PAGE_URL);`,
      `await expect(page.locator(${q(selectors[0])}).first()).toBeVisible();`,
    ]);
  }

  // Form without validation: an empty submit must be blocked by validation.
  const formSel = selectors.find((s) => pageEv?.forms.some((fm) => fm.selector === s)) ??
    (/\bform|validation\b/i.test(f.title) ? selectors[0] : undefined);
  if (formSel) {
    return block(name, ['page'], [
      `await page.goto(PAGE_URL);`,
      `const form = page.locator(${q(formSel)}).first();`,
      `// Stop a real submission so the check has no side effects.`,
      `await form.evaluate((el) => el.addEventListener('submit', (e) => e.preventDefault(), { capture: true }));`,
      `await form.locator('[type=submit], button:not([type=button])').first().click();`,
      `expect(await form.locator(':invalid').count()).toBeGreaterThan(0);`,
    ]);
  }

  // Broken links / failed requests: every URL must answer with status < 400.
  const urls = f.evidence.filter((e) => e.kind === 'link' || e.kind === 'network').map((e) => resolveUrl(e.value, url));
  if (urls.length > 0) {
    return block(name, ['request'], [
      `for (const href of ${JSON.stringify([...new Set(urls)])}) {`,
      `  const res = await request.get(href, { failOnStatusCode: false });`,
      `  expect(res.status(), href).toBeLessThan(400);`,
      `}`,
    ]);
  }

  // Console errors: loading the page must not log them.
  const consoleTexts = f.evidence.filter((e) => e.kind === 'console').map((e) => e.value.slice(0, 120));
  if (consoleTexts.length > 0) {
    return block(name, ['page'], [
      `const errors: string[] = [];`,
      `page.on('console', (msg) => { if (msg.type() === 'error') errors.push(msg.text()); });`,
      `page.on('pageerror', (err) => errors.push(err.message));`,
      `await page.goto(PAGE_URL);`,
      `await page.waitForLoadState('networkidle').catch(() => {});`,
      `for (const text of ${JSON.stringify(consoleTexts)}) {`,
      `  expect(errors.filter((e) => e.includes(text)), text).toHaveLength(0);`,
      `}`,
    ]);
  }

  // Dead button: clicking must have an observable effect (navigation or DOM change).
  const deadSel = selectors.find((s) => pageEv?.buttons.some((b) => b.selector === s && !b.hasHandler)) ??
    (/button|click|dead|unresponsive|does nothing|no effect/i.test(f.title) ? selectors[0] : undefined);
  if (deadSel) {
    return block(name, ['page'], [
      `await page.goto(PAGE_URL);`,
      `await page.evaluate(() => {`,
      `  const w = window as unknown as { __uiaMutations: number };`,
      `  w.__uiaMutations = 0;`,
      `  new MutationObserver((m) => { w.__uiaMutations += m.length; })`,
      `    .observe(document.documentElement, { subtree: true, childList: true, attributes: true, characterData: true });`,
      `});`,
      `const before = page.url();`,
      `await page.locator(${q(deadSel)}).first().click();`,
      `await page.waitForTimeout(1000);`,
      `const changed = page.url() !== before ||`,
      `  (await page.evaluate(() => (window as unknown as { __uiaMutations: number }).__uiaMutations > 0).catch(() => true));`,
      `expect(changed, 'clicking should navigate or change the page').toBe(true);`,
    ]);
  }

  // Fallback: document the manual steps.
  const lines = [
    `// Could not be automated from the evidence. Steps to reproduce:`,
    ...f.stepsToReproduce.map((s, i) => `// ${i + 1}. ${oneLine(s)}`),
    `// Expected: ${oneLine(f.expected)}`,
    `// Actual: ${oneLine(f.actual)}`,
  ];
  return `  test.fixme(${name}, async () => {\n${lines.map((l) => `    ${l}`).join('\n')}\n  });`;
}

function block(name: string, fixtures: string[], lines: string[]): string {
  return `  test(${name}, async ({ ${fixtures.join(', ')} }) => {\n${lines.map((l) => `    ${l}`).join('\n')}\n  });`;
}

function isHiddenCta(f: Finding, pageEv: PageEvidence | undefined): boolean {
  if (f.category !== 'UX' || f.viewport === 'all') return false;
  const selectors = f.evidence.filter((e) => e.kind === 'selector').map((e) => e.value);
  if (selectors.length === 0) return false;
  const capture = pageEv?.captures.find((c) => c.viewport === f.viewport);
  if (capture?.hiddenCtas.some((h) => selectors.includes(h.selector))) return true;
  return /hidden|invisible|not visible|missing on/i.test(f.title);
}

function findPage(bundle: EvidenceBundle, page: string): PageEvidence | undefined {
  const target = resolveUrl(page, bundle.startUrl);
  return bundle.pages.find((p) => p.url === page || p.url === target || norm(p.url) === norm(target));
}

function resolveUrl(value: string, base: string): string {
  try {
    return new URL(value, base).href;
  } catch {
    return value;
  }
}

function norm(u: string): string {
  return u.replace(/#.*$/, '').replace(/\/+$/, '');
}

function pathOf(url: string): string {
  try {
    return new URL(url).pathname || '/';
  } catch {
    return url;
  }
}

function slugFor(url: string): string {
  const slug = pathOf(url)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60);
  return slug || 'home';
}

/** Safe TS string literal. */
function q(s: string): string {
  // Escape U+2028 / U+2029 (line / paragraph separator) so the literal stays on one line.
  return JSON.stringify(s).replace(LINE_SEPS, (c) => '\\u' + c.charCodeAt(0).toString(16));
}

/** Text safe inside a // comment. */
function oneLine(s: string): string {
  return s.replace(/[\r\n]+/g, ' ').replace(LINE_SEPS, ' ').trim();
}

const LINE_SEPS = new RegExp(`[${String.fromCharCode(0x2028, 0x2029)}]`, 'g');
